def get_coding_skill_score(row):
    rating = row['coding_contest_rating']
    score = 25
    if row['coding_contest_platform'] == "Codeforces":
        if rating < 1200:
            return 1*score  # Newbie/Beginner
        elif 1200 <= rating <= 1599:
            return 2*score  # Intermediate (Pupil/Specialist)
        elif 1600 <= rating <= 2099:
            return 3*score  # Advanced (Expert/Candidate Master)
        else: # rating >= 2100
            return 4*score  # Elite (Master+)

    elif row['coding_contest_platform'] == "CodeChef":
        if rating < 1400:
            return 1*score  # Newbie/Beginner
        elif 1400 <= rating <= 1799:
            return 2*score  # Intermediate (Pupil/Specialist)
        elif 1800 <= rating <= 2199:
            return 3*score  # Advanced (Expert/Candidate Master)
        else: # rating >= 2200
            return 4*score  # Elite (Master+)

    elif row['coding_contest_platform'] == "LeetCode":
        if rating < 1500:
            return 1*score  # Newbie/Beginner
        elif 1500 <= rating <= 1899:
            return 2*score  # Intermediate (Pupil/Specialist)
        elif 1900 <= rating <= 2300:
            return 3*score  # Advanced (Expert/Candidate Master)
        else: # rating >= 2400
            return 4*score  # Elite (Master+)

    elif row['coding_contest_platform'] == "HackerRank":
        if rating < 1600:
            return 1*score  # Newbie/Beginner
        elif 1600 <= rating <= 2000:
            return 2*score  # Intermediate (Pupil/Specialist)
        elif 2000 <= rating <= 2400:
            return 3*score  # Advanced (Expert/Candidate Master)
        else: # rating >= 2500
            return 4*score  # Elite (Master+)

    # For any other platform not explicitly listed or if all platform flags are 0 (should not happen with one-hot encoding if one platform is always present)
    return 0 # Default or unknown category





